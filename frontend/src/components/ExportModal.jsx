import React from 'react';
import { X, Download, FileSpreadsheet, FileJson, CheckCircle2 } from 'lucide-react';

export default function ExportModal({ transactions, taxSummary, onClose }) {
  const downloadTransactionsCsv = () => {
    const headers = [
      'Date',
      'Original Description',
      'Cleaned Merchant',
      'Amount',
      'Category',
      'Confidence Score',
      'Schedule C Line',
      'Deductibility %',
      'Deductible Amount',
      'Notes',
    ];

    const rows = transactions.map((tx) => [
      `"${tx.date || ''}"`,
      `"${(tx.raw_description || '').replace(/"/g, '""')}"`,
      `"${(tx.cleaned_merchant || '').replace(/"/g, '""')}"`,
      tx.amount,
      `"${tx.category}"`,
      tx.confidence,
      `"${tx.schedule_c_line}"`,
      `${tx.deductibility_pct * 100}%`,
      tx.deductible_amount,
      `"${(tx.notes || '').replace(/"/g, '""')}"`,
    ]);

    const csvContent = [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', 'categorized_transactions_statement.csv');
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const downloadTaxSummaryCsv = () => {
    const lines = [
      'IRS Schedule C Tax Summary Report',
      'Generated by TaxBrain Statement Categorizer',
      '',
      `Gross Business Income (Line 1),$${taxSummary.gross_income.toFixed(2)}`,
      `Total Raw Expenses,$${taxSummary.total_raw_expenses.toFixed(2)}`,
      `Total Deductible Expenses,$${taxSummary.total_deductible_expenses.toFixed(2)}`,
      `Refunds & Returns Offset,$${taxSummary.total_refunds_offset.toFixed(2)}`,
      `Non-Expense Transfers/Draws Excluded,$${taxSummary.total_non_expense_transfers.toFixed(2)}`,
      `Net Taxable Profit (Line 31),$${taxSummary.net_taxable_profit.toFixed(2)}`,
      '',
      'Category,Schedule C Line,Total Amount,Deductible Amount,Deductibility %,Count',
      ...taxSummary.categories.map(
        (c) =>
          `"${c.category}","${c.schedule_c_line}",$${c.total_amount.toFixed(2)},$${c.deductible_amount.toFixed(2)},${c.deductibility_pct * 100}%,${c.transaction_count}`
      ),
    ];

    const blob = new Blob([lines.join('\n')], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', 'schedule_c_tax_summary.csv');
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const downloadTaxSummaryJson = () => {
    const payload = {
      tax_summary: taxSummary,
      transactions: transactions,
      generated_at: new Date().toISOString(),
    };
    const blob = new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', 'schedule_c_tax_summary.json');
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  return (
    <div className="modal-overlay" onClick={onClose}>
      <div
        className="glass-panel modal-content"
        onClick={(e) => e.stopPropagation()}
        style={{
          width: '100%',
          maxWidth: 480,
          padding: '24px',
          background: 'rgba(16, 21, 33, 0.95)',
          border: '1px solid var(--border-hover)',
        }}
      >
        <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: 16 }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
            <div style={{
              width: 34,
              height: 34,
              borderRadius: 8,
              background: 'rgba(99, 102, 241, 0.15)',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'center',
            }}>
              <Download size={18} color="#818cf8" />
            </div>
            <div>
              <h2 style={{ fontSize: '1.05rem', fontWeight: 700, color: 'var(--text-primary)' }}>
                Export Reports
              </h2>
              <span style={{ fontSize: '0.75rem', color: 'var(--text-muted)' }}>
                Download audit-ready files for your CPA or tax software
              </span>
            </div>
          </div>

          <button
            onClick={onClose}
            style={{
              background: 'transparent',
              border: 'none',
              color: 'var(--text-muted)',
              cursor: 'pointer',
              padding: 4,
            }}
          >
            <X size={18} />
          </button>
        </div>

        <div style={{ display: 'flex', flexDirection: 'column', gap: 10, marginTop: 8 }}>
          {/* Option 1: Full Categorized Transactions CSV */}
          <div
            onClick={downloadTransactionsCsv}
            className="glass-panel"
            style={{
              padding: '14px 16px',
              cursor: 'pointer',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              transition: 'all 0.15s ease',
            }}
            onMouseEnter={(e) => (e.currentTarget.style.borderColor = 'var(--accent-indigo)')}
            onMouseLeave={(e) => (e.currentTarget.style.borderColor = 'var(--border-subtle)')}
          >
            <div style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
              <FileSpreadsheet size={20} color="#34d399" />
              <div>
                <div style={{ fontSize: '0.88rem', fontWeight: 600, color: 'var(--text-primary)' }}>
                  Categorized Transactions (.CSV)
                </div>
                <div style={{ fontSize: '0.74rem', color: 'var(--text-muted)' }}>
                  All rows with cleaned merchants, Schedule C tags, and notes
                </div>
              </div>
            </div>
            <Download size={16} color="var(--text-muted)" />
          </div>

          {/* Option 2: Schedule C Tax Summary CSV */}
          <div
            onClick={downloadTaxSummaryCsv}
            className="glass-panel"
            style={{
              padding: '14px 16px',
              cursor: 'pointer',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              transition: 'all 0.15s ease',
            }}
            onMouseEnter={(e) => (e.currentTarget.style.borderColor = 'var(--accent-indigo)')}
            onMouseLeave={(e) => (e.currentTarget.style.borderColor = 'var(--border-subtle)')}
          >
            <div style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
              <FileSpreadsheet size={20} color="#818cf8" />
              <div>
                <div style={{ fontSize: '0.88rem', fontWeight: 600, color: 'var(--text-primary)' }}>
                  IRS Schedule C Summary (.CSV)
                </div>
                <div style={{ fontSize: '0.74rem', color: 'var(--text-muted)' }}>
                  Form 1040 line item deductions, meals limit, and net profit
                </div>
              </div>
            </div>
            <Download size={16} color="var(--text-muted)" />
          </div>

          {/* Option 3: Full Audit Package JSON */}
          <div
            onClick={downloadTaxSummaryJson}
            className="glass-panel"
            style={{
              padding: '14px 16px',
              cursor: 'pointer',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              transition: 'all 0.15s ease',
            }}
            onMouseEnter={(e) => (e.currentTarget.style.borderColor = 'var(--accent-indigo)')}
            onMouseLeave={(e) => (e.currentTarget.style.borderColor = 'var(--border-subtle)')}
          >
            <div style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
              <FileJson size={20} color="#f59e0b" />
              <div>
                <div style={{ fontSize: '0.88rem', fontWeight: 600, color: 'var(--text-primary)' }}>
                  Audit Package (.JSON)
                </div>
                <div style={{ fontSize: '0.74rem', color: 'var(--text-muted)' }}>
                  Complete structured schema for automated tax software import
                </div>
              </div>
            </div>
            <Download size={16} color="var(--text-muted)" />
          </div>
        </div>
      </div>
    </div>
  );
}
