"""Domain enumerations shared by every layer."""

from enum import StrEnum


class Direction(StrEnum):
    INFLOW = "inflow"
    OUTFLOW = "outflow"


class AccountType(StrEnum):
    CHECKING = "checking"
    CREDIT_CARD = "credit_card"


class SourceFormat(StrEnum):
    CSV = "csv"
    OFX = "ofx"


class Status(StrEnum):
    AUTO = "auto"
    NEEDS_REVIEW = "needs_review"
    USER_CONFIRMED = "user_confirmed"
    DUPLICATE = "duplicate"


class CategoryKind(StrEnum):
    INCOME = "income"
    EXPENSE = "expense"
    NON_PNL = "non_pnl"


class Category(StrEnum):
    # Income (Schedule E line 3)
    RENT = "RENT"
    # Expenses (Schedule E lines 5-19)
    ADVERTISING = "ADVERTISING"
    AUTO_TRAVEL = "AUTO_TRAVEL"
    CLEANING_MAINTENANCE = "CLEANING_MAINTENANCE"
    COMMISSIONS = "COMMISSIONS"
    INSURANCE = "INSURANCE"
    LEGAL_PROFESSIONAL = "LEGAL_PROFESSIONAL"
    MANAGEMENT_FEES = "MANAGEMENT_FEES"
    MORTGAGE_INTEREST = "MORTGAGE_INTEREST"
    OTHER_INTEREST = "OTHER_INTEREST"
    REPAIRS = "REPAIRS"
    SUPPLIES = "SUPPLIES"
    TAXES = "TAXES"
    UTILITIES = "UTILITIES"
    OTHER_EXPENSE = "OTHER_EXPENSE"
    # Not counted on Schedule E
    SECURITY_DEPOSIT_RECEIVED = "SECURITY_DEPOSIT_RECEIVED"
    SECURITY_DEPOSIT_RETURNED = "SECURITY_DEPOSIT_RETURNED"
    LOAN_PRINCIPAL = "LOAN_PRINCIPAL"
    CAPITAL_IMPROVEMENT = "CAPITAL_IMPROVEMENT"
    TRANSFER = "TRANSFER"
    CARD_PAYMENT = "CARD_PAYMENT"
    OWNER_CONTRIBUTION = "OWNER_CONTRIBUTION"
    OWNER_DRAW = "OWNER_DRAW"
    PERSONAL = "PERSONAL"
    INTEREST_EARNED = "INTEREST_EARNED"


class Flag(StrEnum):
    MIXED_USE_MERCHANT = "MIXED_USE_MERCHANT"
    POSSIBLE_CAPITAL_IMPROVEMENT = "POSSIBLE_CAPITAL_IMPROVEMENT"
    MORTGAGE_SPLIT_REQUIRED = "MORTGAGE_SPLIT_REQUIRED"
    PAYMENT_TO_INDIVIDUAL = "PAYMENT_TO_INDIVIDUAL"
    CHECK_NO_PAYEE = "CHECK_NO_PAYEE"
    DIRECTION_CONFLICT = "DIRECTION_CONFLICT"
    AMOUNT_OUTLIER = "AMOUNT_OUTLIER"
    UNKNOWN_MERCHANT = "UNKNOWN_MERCHANT"
    LOW_INFORMATION = "LOW_INFORMATION"
    ZERO_AMOUNT = "ZERO_AMOUNT"
    AMBIGUOUS_MATCH = "AMBIGUOUS_MATCH"
    REFUND_EXCEEDS_PURCHASE = "REFUND_EXCEEDS_PURCHASE"
    RENT_REVERSAL = "RENT_REVERSAL"
    POSSIBLE_1099 = "POSSIBLE_1099"
    RECURRING = "RECURRING"
    DUPLICATE_PENDING = "DUPLICATE_PENDING"
    DUPLICATE_FITID = "DUPLICATE_FITID"
    DUPLICATE_PRIOR_UPLOAD = "DUPLICATE_PRIOR_UPLOAD"


# Flags that are informational only; every other flag forces NEEDS_REVIEW.
NON_BLOCKING_FLAGS: frozenset[Flag] = frozenset(
    {Flag.RENT_REVERSAL, Flag.POSSIBLE_1099, Flag.RECURRING}
)
